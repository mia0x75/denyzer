// Package auth hashes and verifies the single administrator's password.
package auth

import (
	"crypto/rand"
	"crypto/subtle"
	"encoding/base64"
	"errors"
	"strings"

	"golang.org/x/crypto/argon2"
)

const (
	// MaxPasswordBytes bounds password input before running the password KDF.
	MaxPasswordBytes = 1024
	memoryKiB        = 64 * 1024
	iterations       = 3
	parallelism      = 2
	saltBytes        = 16
	keyBytes         = 32
	hashPrefix       = "$argon2id$v=19$m=65536,t=3,p=2$"
)

// HashPassword returns an Argon2id PHC string with a fresh random salt.
func HashPassword(password []byte) (string, error) {
	if len(password) == 0 || len(password) > MaxPasswordBytes {
		return "", errors.New("password must contain between 1 and 1024 bytes")
	}

	salt := make([]byte, saltBytes)
	if _, err := rand.Read(salt); err != nil {
		return "", err
	}

	key := argon2.IDKey(password, salt, iterations, memoryKiB, parallelism, keyBytes)

	return hashPrefix + base64.RawStdEncoding.EncodeToString(salt) + "$" +
		base64.RawStdEncoding.EncodeToString(key), nil
}

// ValidateHash accepts only the bounded Argon2id format generated by HashPassword.
func ValidateHash(hash string) error {
	_, _, err := decodeHash(hash)

	return err
}

// VerifyPassword compares the derived key in constant time.
func VerifyPassword(hash string, password []byte) bool {
	if len(password) == 0 || len(password) > MaxPasswordBytes {
		return false
	}

	salt, expected, err := decodeHash(hash)
	if err != nil {
		return false
	}

	key := argon2.IDKey(password, salt, iterations, memoryKiB, parallelism, keyBytes)

	return subtle.ConstantTimeCompare(key, expected) == 1
}

func decodeHash(hash string) ([]byte, []byte, error) {
	encoded, ok := strings.CutPrefix(hash, hashPrefix)
	if !ok {
		return nil, nil, errors.New("invalid argon2id password hash; use denyzer auth to set it")
	}

	saltText, keyText, ok := strings.Cut(encoded, "$")
	if !ok {
		return nil, nil, errors.New("invalid argon2id password hash")
	}

	salt, saltErr := base64.RawStdEncoding.Strict().DecodeString(saltText)
	key, keyErr := base64.RawStdEncoding.Strict().DecodeString(keyText)
	if saltErr != nil || keyErr != nil || len(salt) != saltBytes || len(key) != keyBytes {
		return nil, nil, errors.New("invalid argon2id salt or key")
	}

	return salt, key, nil
}
